window.colegioLibreStaticProducts = colegioLibreStaticProducts;
window.getColegioLibreStaticProducts = function getColegioLibreStaticProducts() {
  return colegioLibreStaticProducts.map((product) => ({ ...product }));
};

window.getColegioLibreStaticProductById = function getColegioLibreStaticProductById(productId) {
  return colegioLibreStaticProducts.find((product) => product.id === productId) || null;
};

async function cargarProductosDesdeSupabase() {
  if (!window.colegioLibreSupabase || typeof window.colegioLibreSupabase.from !== "function") {
    return window.getColegioLibreStaticProducts();
  }

  const { data, error } = await window.colegioLibreSupabase
    .from("products")
    .select("*")
    .order("created_at", { ascending: false });

  if (error || !Array.isArray(data) || !data.length) {
    return window.getColegioLibreStaticProducts();
  }

  return data.map((product) => ({
    id: product.id,
    title: product.title,
    price: Number(product.price || 0),
    location: product.location || "Sin ubicacion",
    condition: product.condition || "Usado",
    category: product.category || "Libros",
    description: product.description || "",
    image_url: product.image_url || "images/materiales.webp",
    seller_name: product.seller_name || "Usuario ColegioLibre",
    user_id: product.user_id || null,
    school_code: product.school_code || null,
    school_name: product.school_name || "Colegio no especificado",
    zone_code: product.zone_code || product.location || "Zona no especificada",
    status: product.status || "available",
    created_at: product.created_at || null,
    views: Number(product.views || 0)
  }));
}

window.cargarProductosDesdeSupabase = cargarProductosDesdeSupabase;
